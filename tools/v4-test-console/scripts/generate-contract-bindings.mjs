function selectAbi(abi, names) {
  const selected = abi.filter((item) => item.name && names.has(item.name));
  const found = new Set(selected.map((item) => item.name));
  const missing = [...names].filter((name) => !found.has(name));
  if (missing.length > 0) throw new Error(`Generated artifact is missing: ${missing.join(", ")}`);
  return selected;
}

